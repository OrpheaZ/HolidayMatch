export function choiceKey(value) {
  return choiceKeys[value] ?? null;
}

export function translateChoice(language, value) {
  const key = choiceKey(value);
  return key ? translate(language, key) : value;
}

export function supportedLanguage(value) {
  const language = typeof value === "string" ? value.toLowerCase().split(/[-_]/)[0] : "";
  return Object.hasOwn(messages, language) ? language : null;
}

export function initialLanguage(stored, browserLanguages = []) {
  return supportedLanguage(stored)
    ?? browserLanguages.map(supportedLanguage).find(Boolean)
    ?? "de";
}

export function translate(language, key, values = {}) {
  const catalog = messages[supportedLanguage(language) ?? "de"];
  if (!Object.hasOwn(catalog, key)) throw new Error(`Unknown translation key: ${key}`);
  return catalog[key].replace(/\{(\w+)\}/g, (match, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : match);
}

export function localeForLanguage(language) {
  return { de: "de-DE", en: "en-GB", bg: "bg-BG" }[supportedLanguage(language) ?? "de"];
}

export function formatTripDateRange(language, start, end) {
  const formatter = new Intl.DateTimeFormat(localeForLanguage(language), {
    day: "numeric", month: "long", year: "numeric",
  });
  return formatter.formatRange(new Date(`${start}T12:00:00`), new Date(`${end}T12:00:00`));
}

export function translateElements(root, language) {
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(language, element.dataset.i18n);
    element.lang = language;
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", translate(language, element.dataset.i18nAriaLabel));
    element.lang = language;
  });
  root.querySelectorAll("[data-i18n-title]").forEach((element) => {
    element.title = translate(language, element.dataset.i18nTitle);
    element.lang = language;
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = translate(language, element.dataset.i18nPlaceholder);
    element.lang = language;
  });
  root.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.alt = translate(language, element.dataset.i18nAlt);
    element.lang = language;
  });
}
